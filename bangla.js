// Text translate function
function translatePage() {

  const elements = document.querySelectorAll(
    "body *"
  );

  elements.forEach(el => {

    if (
      el.children.length === 0 &&
      el.textContent.trim()
    ) {

      const original = el.textContent.trim();

      if (bn[original]) {
        el.textContent =
          el.textContent.replace(
            original,
            bn[original]
          );
      }
    }

  });

  // Inputs
  document.querySelectorAll(
    "input, textarea"
  ).forEach(el => {

    if (el.placeholder && bn[el.placeholder]) {
      el.placeholder = bn[el.placeholder];
    }

  });

  // Select options
  document.querySelectorAll(
    "option"
  ).forEach(el => {

    const text = el.textContent.trim();

    if (bn[text]) {
      el.textContent = bn[text];
    }

  });

}


// Run after page is rendered
setTimeout(translatePage, 100);


// Watch dynamically generated content
const observer = new MutationObserver(() => {
  translatePage();
});

observer.observe(document.body, {
  childList: true,
  subtree: true
});